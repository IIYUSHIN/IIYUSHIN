export const GLYPH_W = 5;
export const GLYPH_H = 7;
export const ADVANCE = 6; // 5px glyph + 1px gap

/** Characters requested but not in the font (drawn as '?'). Checked by the tests. */
export const missing = new Set();

export function glyph(ch) {
  const g = G[ch] ?? G[ch.toUpperCase()];
  if (!g) missing.add(ch);
  return g ?? G['?'];
}

export function hasGlyph(ch) {
  return Boolean(G[ch] ?? G[ch.toUpperCase()]);
}

/** Width in px of `text` at pixel size `s` (no trailing gap). */
export function textWidth(text, s) {
  const n = [...text].length;
  return n === 0 ? 0 : (n * ADVANCE - 1) * s;
}

/**
 * Path data for `text` with its top-left corner at (x, y), pixel size `s`.
 * Horizontal runs are merged into one sub-path each, which keeps files small.
 */
export function textPath(text, x, y, s) {
  let d = '';
  let cx = x;
  for (const ch of text) {
    const rows = glyph(ch);
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      let c = 0;
      while (c < GLYPH_W) {
        if (row[c] !== '#') { c++; continue; }
        let len = 0;
        while (c + len < GLYPH_W && row[c + len] === '#') len++;
        const px = +(cx + c * s).toFixed(2);
        const py = +(y + r * s).toFixed(2);
        d += `M${px} ${py}h${len * s}v${s}h${-len * s}z`;
        c += len;
      }
    }
    cx += ADVANCE * s;
  }
  return d;
}
